export const CHAT_LANGUAGES = { en: "English", ja: "日本語" } as const;
export type ChatLocale = keyof typeof CHAT_LANGUAGES;

export function isChatLocale(value: unknown): value is ChatLocale {
  return typeof value === "string" && Object.hasOwn(CHAT_LANGUAGES, value);
}

export function preferredChatLocale(languages: readonly string[]): ChatLocale {
  for (const language of languages) {
    const base = language.toLowerCase().split("-")[0];
    if (isChatLocale(base)) return base;
  }
  return "en";
}

