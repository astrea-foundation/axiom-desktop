export type ChatMessageKey = keyof typeof messages;
export type ChatTranslator = (key: ChatMessageKey, values?: Record<string, string | number>) => string;

export function chatTranslator(locale: ChatLocale): ChatTranslator {
  return (key, values = {}) => {
    const message: Message = messages[key];
    return (message[locale] ?? message.en).replace(/\{(\w+)\}/g, (placeholder, name) => String(values[name] ?? placeholder));
  };
}
